#!/bin/zsh
# Rebuilds Core/Card/CardFont.swift: Baloo 2 (OFL, https://github.com/EkType/Baloo2) cut down to the
# characters the profile card uses, as WOFF2 in a base64 string the SVG embeds.
# Usage: scripts/build-card-font.sh path/to/Baloo2[wght].ttf
set -euo pipefail
source=${1:?"variable Baloo 2 TTF from https://github.com/google/fonts/tree/main/ofl/baloo2"}
root=${0:A:h:h}
work=$(mktemp -d)
/usr/bin/python3 -m fontTools.subset "$source" --unicodes="U+0020-007E,U+00B7" --flavor=woff2 \
  --layout-features='kern,liga' --name-IDs='0,1,2,3,4,5,6,13,14' --output-file="$work/card.woff2"
{
  echo "// Generated by scripts/build-card-font.sh. Do not edit."
  echo "// Baloo 2, Copyright 2019 The Baloo 2 Project Authors, SIL Open Font License 1.1"
  echo "// (Resources/Fonts/Baloo2-OFL.txt). Subset to ASCII and the middle dot."
  echo ""
  echo "enum CardFont {"
  echo "    static let family = \"Baloo 2\""
  echo "    static let woff2Base64 = \"$(base64 -i "$work/card.woff2" | tr -d '\n')\""
  echo "}"
} > "$root/app/TokenCats/Core/Card/CardFont.swift"
rm -rf "$work"
